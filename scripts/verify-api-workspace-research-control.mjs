import { readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { isVersionAtLeast } from "./version.mjs";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const failures = [];
const assert = (condition, message) => { if (!condition) failures.push(message); };
const text = (path) => readFileSync(join(root, path), "utf8");
const json = (path) => JSON.parse(text(path));
const contract = json("contracts/api-workspace-research-control-contract.json");
const packageJson = json("package.json");
const page = text("src/pages/apiWorkspace.ts");
const settings = text("src/pages/openai.ts");
const main = text("src/main.ts");
const commands = text("src-tauri/src/commands/api_workspace.rs");
const gateway = text("crates/research-gateway/src/client.rs");
assert(contract.release_version === "0.14.0" && isVersionAtLeast(packageJson.version, contract.release_version), "研究控制历史契约或当前项目版本未同步");
assert(contract.surface.global_busy_overlay_during_send === false, "发送期间不得使用全局遮罩");
assert(page.includes("api-local-progress") && page.includes("取消请求"), "发送区缺少局部状态或取消按钮");
assert(main.includes("apiWorkspaceActiveRequestId") && main.includes("cancelApiWorkspaceRequest"), "取消请求状态未接通");
assert(main.includes("apiWorkspaceDraftMessage"), "AI草稿状态未保留");
assert(page.includes("搜索会话") && page.includes("archive-api-workspace-session"), "会话搜索或归档未接通");
assert(page.includes("附加当前只读上下文"), "缺少只读上下文开关");
assert(commands.includes("api_workspace_context") && commands.includes("Do not propose writes"), "后端未约束只读上下文");
assert(settings.includes('id="openai-api-workspace-web-search-mode" type="hidden" value="disabled"'), "AI问答联网能力仍可开启");
assert(!page.includes("api-workspace-token") && !page.includes("max-tool-calls") && !page.includes("tool-choice"), "AI问答页面仍显示Token或工具设置控件");
assert(gateway.includes("P4正式联网研究仅支持Responses协议"), "P4正式研究隔离被破坏");
assert(contract.boundaries.formal_p4_research_unchanged === true, "契约未锁定P4边界");
assert(contract.boundaries.integration_point_h_started === false, "不得提前进入接入点H");
if (failures.length) { console.error("AI问答交互与研究隔离验证失败："); failures.forEach((item) => console.error(`- ${item}`)); process.exit(1); }
console.log("AI问答交互与研究隔离验证通过：局部异步、取消、草稿、只读上下文、禁联网和P4隔离均已锁定。");
