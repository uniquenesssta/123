import { readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { isVersionAtLeast } from "./version.mjs";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const failures = [];
const assert = (condition, message) => { if (!condition) failures.push(message); };
const text = (path) => readFileSync(join(root, path), "utf8");
const json = (path) => JSON.parse(text(path));
const slice = (source, start, end) => { const a = source.indexOf(start); const b = source.indexOf(end, a); return a < 0 ? "" : b < 0 ? source.slice(a) : source.slice(a, b); };
const contract = json("contracts/api-compatible-transport-contract.json");
const packageJson = json("package.json");
const gateway = text("crates/research-gateway/src/client.rs");
const response = text("crates/research-gateway/src/response.rs");
const types = text("crates/research-gateway/src/types.rs");
const tests = text("crates/research-gateway/tests/gateway_contract.rs");
const body = slice(gateway, "fn build_plain_text_request_body", "fn build_structured_request_body");
assert(contract.release_version === "0.14.0" && isVersionAtLeast(packageJson.version, contract.release_version), "兼容传输历史契约或当前项目版本未同步");
assert(contract.request_policy.tools_sent === false, "AI问答不得发送工具");
assert(contract.request_policy.web_search_sent === false, "AI问答不得发送Web Search");
assert(contract.request_policy.token_limit_sent_for_ai_chat === false, "AI问答不得发送Token限制字段");
assert(types.includes("PlainTextGatewayRequest") && types.includes("PlainTextGatewayResponse"), "缺少纯文本传输类型");
assert(gateway.includes("execute_plain_text_with_sink"), "缺少纯文本执行链");
assert(body.includes('"input"') && body.includes('"messages"'), "双协议最小请求体不完整");
for (const field of ["tools", "tool_choice", "json_schema", "max_output_tokens", "max_completion_tokens", "background", "store", "reasoning", "metadata"]) assert(!body.includes(`\"${field}\"`), `纯文本请求意外包含${field}`);
assert(response.includes("extract_responses_text") && response.includes("extract_chat_completions_text"), "纯文本响应未覆盖双协议");
assert(tests.includes("plain_text"), "缺少纯文本网关测试");
assert(gateway.includes("P4正式联网研究仅支持Responses协议"), "P4正式研究协议边界被破坏");
if (failures.length) { console.error("AI问答兼容传输验证失败："); failures.forEach((item) => console.error(`- ${item}`)); process.exit(1); }
console.log("AI问答兼容传输验证通过：Responses与Chat Completions均使用无工具、无Schema、无Token字段的最小文本请求。");
