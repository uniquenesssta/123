import fs from "node:fs";
import crypto from "node:crypto";
import { isVersionAtLeast } from "./version.mjs";
const read = (p) => fs.readFileSync(new URL(`../${p}`, import.meta.url), "utf8");
const contractText = read("contracts/formation-usage-contract.json");
const contract = JSON.parse(contractText);
const migration = read("crates/persistence-postgres/migrations/0022_formations_and_usage.sql");
const domain = read("crates/domain/src/lib.rs");
const persistence = read("crates/persistence-postgres/src/formation_catalog.rs");
const monthlyWorkbooks = read("crates/persistence-postgres/src/monthly_workbooks.rs");
const integrationTests = read("crates/persistence-postgres/tests/postgres_integration.rs");
const spreadsheetApplication = read("crates/application/src/spreadsheet.rs");
const lineupPersistence = read("crates/persistence-postgres/src/player_catalog.rs");
const commands = read("src-tauri/src/commands/catalog.rs");
const registry = read("src-tauri/src/lib.rs");
const client = read("src/api/client.ts");
const teams = read("src/pages/teams.ts");
const lineups = read("src/pages/lineups.ts");
const main = read("src/main.ts");
const pkg = JSON.parse(read("package.json"));
const hash = crypto.createHash("sha256").update(contractText).digest("hex");
const required = (ok, message) => { if (!ok) throw new Error(message); };
required(isVersionAtLeast(pkg.version, contract.release_version), "当前项目版本早于阶段3版本0.16.0");
required(contract.release_version === "0.16.0" && contract.integration_point_h_started === false, "阶段3契约边界错误");
required(migration.includes(hash), "数据库迁移中的阵型契约哈希不匹配");
for (const code of contract.builtin_formations) required(migration.includes(`'${code}'`), `缺少内置阵型: ${code}`);
for (const command of contract.commands) { required(commands.includes(`fn ${command}`) || commands.includes(`fn ${command}(`), `Rust命令缺失: ${command}`); required(registry.includes(command), `Tauri注册缺失: ${command}`); required(client.includes(command), `前端API缺失: ${command}`); }
required(domain.includes("FormationUsageDistributionDraft") && domain.includes("ResolvedFormationDistribution"), "领域阵型契约缺失");
required(persistence.includes("alpha * prior") && persistence.includes("UNKNOWN_FORMATION_ID"), "阵型平滑或未知回退缺失");
required(!persistence.includes("DELETE FROM feature.formation_usage_observations"), "阵型观察必须追加历史，禁止删除覆盖");
for (const level of contract.resolution_priority) required(persistence.includes(level), `解析优先级缺失: ${level}`);
required(lineupPersistence.includes("formation_id") && lineupPersistence.includes("football.formations"), "阵容目录映射缺失");
required(monthlyWorkbooks.includes("已按阵型代码") && monthlyWorkbooks.includes("_resolved_formation_id"), "跨数据库阵型ID按代码重新绑定缺失");
required(monthlyWorkbooks.includes("引用的阵型ID") && monthlyWorkbooks.includes("缺少 formation_code，无法重新绑定"), "过期阵型ID提交保护缺失");
required(integrationTests.includes("monthly_workbook_rebinds_stale_formation_id_by_code"), "过期阵型ID重新绑定集成测试缺失");
required(spreadsheetApplication.includes("完整资料包预检仍有 {preview_blocking} 条冲突或错误") && spreadsheetApplication.includes("readiness_score = readiness_score.min(69)"), "完整资料包阻塞项与就绪分数未同步");
required(teams.includes("阵型目录与使用概率") && teams.includes("save-formation-usage"), "球队阵型编辑器缺失");
required(lineups.includes('paired-${side}-formation-id') && lineups.includes('lineupSideCard("home"') && lineups.includes('lineupSideCard("away"') && main.includes("formation_id"), "双方阵容阵型选择器缺失");
console.log("阶段3阵型目录与概率契约验证通过。");
